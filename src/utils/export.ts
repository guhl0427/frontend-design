/* ------------------------------- F9 DESIGN.md 导出 ------------------------------- */

/**
 * 从已切分的段落中取指定标题的正文（缺失时返回空串）。
 * 统一走 promptSections.splitPrompt，避免在导出层重复实现正则切分。
 */
function designSectionBody(sections: PromptSection[], title: string): string {
  return sections.find((section) => section.title === title)?.body ?? '';
}

/**
 * 生成单条风格的 DESIGN.md（严格对齐 awesome-design-md 事实标准结构）：
 * 标题 + 摘要引用块 + 8 个章节（Overview / Color Palette / Typography /
 * Shape & Depth / Components / Do's & Don'ts / 分隔线署名）。
 */
export function buildDesignMd(item: StyleItem): string {
  const sections = splitPrompt(item.prompt);
  const p = item.preview.palette;

  return [
    `# ${item.nameZh}（${item.nameEn}）`,
    '',
    `> ${item.summary}`,
    `> 分类：${item.category} · 标签：${item.tags.join(' / ')}`,
    '',
    '## Overview',
    designSectionBody(sections, '设计理念'),
    '',
    '## Color Palette',
    '',
    '| Token | Value | 用途 |',
    '| --- | --- | --- |',
    `| background | ${p.bg} | 页面背景 |`,
    `| surface | ${p.surface} | 卡片 / 面板 |`,
    `| text | ${p.text} | 主文字 |`,
    `| text-muted | ${p.textMuted} | 次级文字 |`,
    `| accent | ${p.accent} | 强调色 / CTA |`,
    `| accent-text | ${p.accentText} | 强调色上的文字 |`,
    `| border | ${p.border} | 边框 |`,
    `| shadow | ${p.shadowColor} | 阴影 / 发光 |`,
    '',
    '## Typography',
    `- 标题字体：\`${item.preview.headingFont}\`，字重 ${item.preview.titleWeight}，字距 \`${item.preview.titleLetterSpacing}\``,
    `- 正文字体：\`${item.preview.bodyFont}\``,
    `- 标题全大写：${item.preview.uppercaseTitle ? '是' : '否'}`,
    '',
    '## Shape & Depth',
    `- 圆角：\`${item.preview.radius}\``,
    `- 边框宽度：\`${item.preview.borderWidth}\``,
    `- 阴影：\`${item.preview.shadow}\``,
    `- 卡片变体：\`${item.preview.cardVariant}\` · 按钮变体：\`${item.preview.buttonVariant}\``,
    '',
    '## Components',
    designSectionBody(sections, '组件规则'),
    '',
    "## Do's & Don'ts",
    designSectionBody(sections, '反模式禁令'),
    '',
    '---',
    `Generated by 前端风格提示词画廊 · ${dashedDateStamp()}`,
    '',
  ].join('\n');
}

/** 生成多条风格的 DESIGN.md 合集：总览（时间 / 数量 / 目录）+ 逐篇完整 DESIGN.md */
export function buildDesignMdBundle(items: StyleItem[]): string {
  const toc = items.map((item, index) => `${index + 1}. ${item.nameZh} · ${item.nameEn}`);
  const bodies = items.map((item, index) =>
    [`## ${index + 1}. ${item.nameZh} · ${item.nameEn}`, '', buildDesignMd(item).trim()].join('\n'),
  );

  return [
    '# DESIGN.md 合集 · 前端风格提示词画廊',
    '',
    `- 导出时间：${new Date().toLocaleString('zh-CN')}`,
    `- 风格数量：${items.length}`,
    '',
    '## 目录',
    '',
    ...toc,
    '',
    '---',
    '',
    bodies.join('\n\n---\n\n'),
    '',
  ].join('\n');
}

